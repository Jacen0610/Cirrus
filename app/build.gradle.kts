android {
    namespace = "si.jacen.cirrus"
    compileSdk {
        version = release(37)
    }

    defaultConfig {
        applicationId = "si.jacen.cirrus"
        minSdk = 29
        targetSdk = 37
        versionCode = 1
        versionName = "1.0"

        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
    }

    signingConfigs {
        // 签名文件 keystore.properties 不入库（见 .gitignore）；
        // 缺失时构建未签名 release APK，本地发布前自行生成 keystore 并填写
        create("release") {
            if (keystoreProperties.containsKey("storeFile")) {
                storeFile = rootProject.file(keystoreProperties["storeFile"] as String)
                storePassword = keystoreProperties["storePassword"] as String
                keyAlias = keystoreProperties["keyAlias"] as String
                keyPassword = keystoreProperties["keyPassword"] as String
            }
        }
    }
    buildTypes {
        release {
            if (keystoreProperties.containsKey("storeFile")) {
                signingConfig = signingConfigs.getByName("release")
            }
            optimization {
                enable = true
                packageScope = setOf("androidx.**", "kotlin.**", "kotlinx.**")
            }
        }
    }
    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_11
        targetCompatibility = JavaVersion.VERSION_11
    }
    buildFeatures {
        compose = true
    }
}

configurations.all {
    resolutionStrategy {
        // AGP 内置 Kotlin 2.2 无法读取 Kotlin 2.4 元数据；Coil 等新库把 stdlib
        // 抬到了 2.4.x，这里对齐回编译器版本。内置 Kotlin 升到 2.4 后可移除。
        force("org.jetbrains.kotlin:kotlin-stdlib:2.2.10")
    }
}

